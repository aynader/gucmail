def normalize_theme_identifier(value: str) -> str:
    """Return the canonical theme ID for config, environment, and legacy values.

    Textual theme names generated by older builds used a ``gucmail-`` prefix.  They
    are accepted here as an interchange format, but configuration always exposes the
    stable catalog identifier (for example ``builtin.default-dark``).
    """

    normalized = value.strip().casefold()
    aliased = _LEGACY_THEME_IDENTIFIERS.get(normalized)
    if aliased is not None:
        return aliased
    for legacy_prefix, canonical_prefix in (
        ("gucmail-builtin-", "builtin."),
        ("gucmail-custom-", "custom."),
    ):
        if normalized.startswith(legacy_prefix):
            suffix = normalized.removeprefix(legacy_prefix)
            return f"{canonical_prefix}{suffix}" if suffix else normalized
    if normalized.startswith(("builtin.", "custom.")):
        return normalized
    return value.strip()


def _parse_bool(value: str) -> bool:
    normalized = value.strip().lower()
    if normalized in {"1", "true", "yes", "on"}:
        return True
    if normalized in {"0", "false", "no", "off"}:
        return False
    raise ValueError(f"expected a boolean, got {value!r}")


@dataclass(frozen=True, slots=True)
class AppPaths:
    config_dir: Path
    data_dir: Path
    cache_dir: Path
    log_dir: Path
    config_file: Path
    state_database: Path
    recovery_dir: Path
    index_database: Path
    backup_dir: Path

    @classmethod
    def discover(cls) -> AppPaths:
        dirs = PlatformDirs(APP_SLUG, APP_AUTHOR, roaming=True, ensure_exists=False)
        config_dir = Path(os.environ.get("GUCMAIL_CONFIG_DIR", dirs.user_config_dir))
        data_dir = Path(os.environ.get("GUCMAIL_DATA_DIR", dirs.user_data_dir))
        cache_dir = Path(os.environ.get("GUCMAIL_CACHE_DIR", dirs.user_cache_dir))
        log_dir = Path(os.environ.get("GUCMAIL_LOG_DIR", dirs.user_log_dir))
        config_file = Path(os.environ.get("GUCMAIL_CONFIG", config_dir / "config.toml"))
        return cls(
            config_dir=config_dir,
            data_dir=data_dir,
            cache_dir=cache_dir,
            log_dir=log_dir,
            config_file=config_file,
            state_database=data_dir / "state.sqlite3",
            recovery_dir=data_dir / "recovery",
            index_database=data_dir / "index.sqlite3",
            backup_dir=data_dir / "backups",
        )

    def ensure(self) -> None:
        for directory in (
            self.config_dir,
            self.data_dir,
            self.cache_dir,
            self.log_dir,
            self.recovery_dir,
            self.backup_dir,
        ):
            directory.mkdir(parents=True, exist_ok=True)


@dataclass(frozen=True, slots=True)
class AppConfig:
    """Core non-secret configuration consumed by the application services."""

    email: str | None = None
    username: str | None = None
    endpoint: str = DEFAULT_EWS_ENDPOINT
    default_folder: str = "inbox"
    page_size: int = DEFAULT_PAGE_SIZE
    poll_interval_seconds: int = DEFAULT_POLL_INTERVAL_SECONDS
    theme: str = "builtin.default-dark"
    no_color: bool = False
    datetime_format: str = "%Y-%m-%d %H:%M %Z"
    timezone: str = "Africa/Cairo"
    external_editor: str | None = None
    download_directory: str | None = None
    signature: str = ""
    allow_remote_content: bool = False
    cache_enabled: bool = True
    cache_message_bodies: bool = False
    index_attachments: bool = False
    semantic_search_enabled: bool = False
    monitoring_enabled: bool = False
    command_hooks_enabled: bool = False
    request_timeout_seconds: int = DEFAULT_REQUEST_TIMEOUT_SECONDS
    retry_attempts: int = 3
    retry_base_seconds: float = 2.0
    retry_max_seconds: float = 120.0
    max_attachment_bytes: int = DEFAULT_MAX_ATTACHMENT_BYTES
    autosave_seconds: int = DEFAULT_AUTOSAVE_SECONDS
    undo_send_seconds: int = 0
    logging_level: str = "WARNING"
    redact_email_addresses: bool = True
    mode: str = "basic"
    onboarding_complete: bool = False
    expert_raw_soap_enabled: bool = False

    def validate(self, *, allow_unsafe_poll_interval: bool = False) -> AppConfig:
        _validate_dataclass_types(self)
        parsed = urlparse(self.endpoint)
        if parsed.scheme != "https" or not parsed.hostname:
            raise ConfigurationError("The EWS endpoint must be a valid HTTPS URL.")
        try:
            _ = parsed.port
        except ValueError as exc:
            raise ConfigurationError("The EWS endpoint contains an invalid port.") from exc
        if parsed.username is not None or parsed.password is not None:
            raise ConfigurationError("The EWS endpoint may not contain credentials.")
        if parsed.params or parsed.query or parsed.fragment:
            raise ConfigurationError(
                "The EWS endpoint may not contain parameters, a query string, or a fragment."
            )
        if not 1 <= self.page_size <= MAX_PAGE_SIZE:
            raise ConfigurationError(f"page_size must be between 1 and {MAX_PAGE_SIZE}.")
        if (
            self.poll_interval_seconds < SAFE_MINIMUM_POLL_INTERVAL_SECONDS
            and not allow_unsafe_poll_interval
        ):
            raise ConfigurationError(
                f"poll_interval_seconds must be at least {SAFE_MINIMUM_POLL_INTERVAL_SECONDS}; "
                "shorter intervals require the explicit advanced override."
            )
        if self.request_timeout_seconds < 1:
            raise ConfigurationError("request_timeout_seconds must be positive.")
        if not 0 <= self.retry_attempts <= 10:
            raise ConfigurationError("retry_attempts must be between 0 and 10.")
        if self.retry_base_seconds <= 0 or self.retry_max_seconds <= 0:
            raise ConfigurationError("retry delays must be positive.")
        if self.retry_max_seconds < self.retry_base_seconds:
            raise ConfigurationError("retry_max_seconds must not be less than retry_base_seconds.")
        if self.max_attachment_bytes < 1:
            raise ConfigurationError("max_attachment_bytes must be positive.")
        if self.autosave_seconds < 5:
            raise ConfigurationError("autosave_seconds must be at least 5 seconds.")
        if self.undo_send_seconds < 0:
            raise ConfigurationError("undo_send_seconds may not be negative.")
        if self.mode not in {"basic", "advanced", "expert"}:
            raise ConfigurationError("mode must be basic, advanced, or expert.")
        if self.logging_level.upper() not in {"CRITICAL", "ERROR", "WARNING", "INFO", "DEBUG"}:
            raise ConfigurationError(
                "logging_level must be CRITICAL, ERROR, WARNING, INFO, or DEBUG."
            )
        try:
            ZoneInfo(self.timezone)
        except ZoneInfoNotFoundError as exc:
            raise ConfigurationError(f"Unknown time zone: {self.timezone}") from exc
        return self

    @property
    def downloads(self) -> Path:
        if self.download_directory:
            return Path(self.download_directory).expanduser()
        return Path.home() / "Downloads" / "GUC Mail"

    def redacted_dict(self) -> dict[str, Any]:
        """Return fail-closed metadata suitable for status and diagnostics."""

        data = asdict(self)
        if data["email"]:
            local, separator, domain = str(data["email"]).partition("@")
            data["email"] = f"{local[:1]}***{separator}{domain}" if separator else "<configured>"
        if data["username"]:
            data["username"] = "<configured>"
        parsed = urlparse(self.endpoint)
        try:
            port = f":{parsed.port}" if parsed.port is not None else ""
        except ValueError:
            port = ""
        if parsed.scheme == "https" and parsed.hostname:
            standard_path = (
                parsed.path
                if parsed.path.casefold().rstrip("/") == "/ews/exchange.asmx"
                else "/<custom-path>"
            )
            data["endpoint"] = f"https://{parsed.hostname}{port}{standard_path}"
        else:
            data["endpoint"] = "<configured>"
        for private_field in (
            "default_folder",
            "external_editor",
            "download_directory",
            "signature",
        ):
            data[private_field] = "<configured>" if data[private_field] else data[private_field]

        # Keep this allowlist explicit so a future private field is not exposed by accident.
        safe_fields = (
            "email",
            "username",
            "endpoint",
            "default_folder",
            "page_size",
            "poll_interval_seconds",
            "theme",
            "no_color",
            "datetime_format",
            "timezone",
            "external_editor",
            "download_directory",
            "signature",
            "allow_remote_content",
            "cache_enabled",
            "cache_message_bodies",
            "index_attachments",
            "semantic_search_enabled",
            "monitoring_enabled",
            "command_hooks_enabled",
            "request_timeout_seconds",
            "retry_attempts",
            "retry_base_seconds",
            "retry_max_seconds",
            "max_attachment_bytes",
            "autosave_seconds",
            "undo_send_seconds",
            "logging_level",
            "redact_email_addresses",
            "mode",
            "onboarding_complete",
            "expert_raw_soap_enabled",
        )
        return {name: data[name] for name in safe_fields}


def _validate_dataclass_types(config: AppConfig) -> None:
    defaults = AppConfig()
    optional_strings = {"email", "username", "external_editor", "download_directory"}
    for item in fields(AppConfig):
        value = getattr(config, item.name)
        default = getattr(defaults, item.name)
        valid = True
        if item.name in optional_strings:
            valid = value is None or isinstance(value, str)
        elif isinstance(default, bool):
            valid = isinstance(value, bool)
        elif isinstance(default, int):
            valid = isinstance(value, int) and not isinstance(value, bool)
        elif isinstance(default, float):
            valid = isinstance(value, (int, float)) and not isinstance(value, bool)
        elif isinstance(default, str):
            valid = isinstance(value, str)
        if not valid:
            raise ConfigurationError(f"{item.name} has the wrong value type.")



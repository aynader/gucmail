@dataclass(frozen=True, slots=True)
class ConfigDiagnostics:
    """Explicit outcome of the most recent configuration load."""

    source: str
    schema_version: int
    recovered: bool = False
    migrated_from: int | None = None
    future_schema: bool = False
    quarantined_paths: tuple[Path, ...] = ()
    migration_backups: tuple[Path, ...] = ()
    messages: tuple[str, ...] = ()

    def as_dict(self) -> dict[str, Any]:
        return {
            "source": self.source,
            "schema_version": self.schema_version,
            "recovered": self.recovered,
            "migrated_from": self.migrated_from,
            "future_schema": self.future_schema,
            "quarantined_paths": [str(path) for path in self.quarantined_paths],
            "migration_backups": [str(path) for path in self.migration_backups],
            "messages": list(self.messages),
        }



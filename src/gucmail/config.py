@dataclass(slots=True)
class _DecodedDocument:
    schema_version: int
    stored_config: AppConfig
    settings: dict[str, Any]
    mapping: dict[str, Any]
    migrated_from: int | None
    migration_messages: list[str]
    future_schema: bool


class ConfigStore:
    """Crash-safe configuration storage with migration and recovery."""

    def __init__(self, paths: AppPaths | None = None) -> None:
        self.paths = paths or AppPaths.discover()
        self._mapping: dict[str, Any] = {}
        self._stored_config = AppConfig()
        self._effective_config = self._stored_config
        self._settings: dict[str, Any] = {}
        self._sources: dict[str, str] = {}
        self._schema_version = CURRENT_CONFIG_SCHEMA_VERSION
        self._revision: str | None = None
        self._loaded = False
        self._diagnostics = ConfigDiagnostics("defaults", CURRENT_CONFIG_SCHEMA_VERSION)

    @property
    def diagnostics(self) -> ConfigDiagnostics:
        return self._diagnostics

    @property
    def revision(self) -> str | None:
        return self._revision

    @property
    def last_known_good_path(self) -> Path:
        return self.paths.config_file.with_name(self.paths.config_file.name + ".lkg")

    @property
    def revisions_directory(self) -> Path:
        return self.paths.config_file.with_name(self.paths.config_file.name + ".revisions")

    def load(self) -> AppConfig:
        return self.load_document().effective_config

    def load_document(self) -> ConfigDocument:
        primary = self.paths.config_file
        quarantined: list[Path] = []
        messages: list[str] = []
        migration_backups: list[Path] = []
        recovered = False
        source = "defaults"
        original: bytes | None = None
        source_content: bytes | None = None
        decoded: _DecodedDocument | None = None
        primary_was_present = primary.exists()
        revision: str | None = None

        if primary_was_present:
            try:
                original = primary.read_bytes()
                revision = hashlib.sha256(original).hexdigest()
                decoded = _decode_document(original)
                source_content = original
                source = "primary"
            except (OSError, UnicodeError, tomllib.TOMLDecodeError, ConfigurationError) as exc:
                quarantined_path = self._quarantine(primary, original)
                if quarantined_path is not None:
                    quarantined.append(quarantined_path)
                messages.append(f"Primary configuration was invalid: {type(exc).__name__}.")

        if decoded is None and self.last_known_good_path.exists():
            try:
                lkg_content = self.last_known_good_path.read_bytes()
                decoded = _decode_document(lkg_content)
                source_content = lkg_content
                source = "last-known-good"
                recovered = True
                messages.append("Recovered the last known working configuration.")
                self.paths.ensure()
            except (OSError, UnicodeError, tomllib.TOMLDecodeError, ConfigurationError) as exc:
                messages.append(f"Last-known-good configuration was invalid: {type(exc).__name__}.")
            else:
                try:
                    self._repair_document(
                        lkg_content,
                        expected_revision=revision,
                        baseline_known=not primary_was_present or original is not None,
                    )
                    revision = hashlib.sha256(lkg_content).hexdigest()
                except OSError:
                    messages.append(
                        "Recovered settings are active in memory, but the repaired file "
                        "could not be saved."
                    )

        if decoded is None:
            defaults_content = _mapping_to_toml(_default_document()).encode("utf-8")
            decoded = _decode_document(defaults_content)
            source = "defaults"
            if primary_was_present:
                recovered = True
                messages.append("Started with safe defaults; the damaged file was preserved.")
                try:
                    self.paths.ensure()
                    repair_warning = self._repair_document(
                        defaults_content,
                        expected_revision=revision,
                        baseline_known=original is not None,
                        update_recovery=True,
                    )
                    revision = hashlib.sha256(defaults_content).hexdigest()
                    if repair_warning:
                        messages.append(repair_warning)
                except OSError:
                    messages.append(
                        "Safe defaults are active in memory, but the repaired file could not "
                        "be saved."
                    )

        migrated_from = decoded.migrated_from
        future_schema = decoded.future_schema
        if decoded.migrated_from is not None and source != "defaults":
            backup = self._migration_backup(source_content, decoded.migrated_from)
            if backup is not None:
                migration_backups.append(backup)
            migrated_content = _mapping_to_toml(decoded.mapping).encode("utf-8")
            repair_warning = self._repair_document(
                migrated_content,
                expected_revision=revision,
                baseline_known=not primary_was_present or original is not None,
                update_recovery=True,
            )
            revision = hashlib.sha256(migrated_content).hexdigest()
            if repair_warning:
                messages.append(repair_warning)
            messages.extend(decoded.migration_messages)
            # Decode the committed representation so future unknown keys are exactly those saved.
            decoded = _decode_document(migrated_content)

        effective, sources = _apply_environment(decoded.stored_config)
        self._mapping = copy.deepcopy(decoded.mapping)
        self._stored_config = decoded.stored_config
        self._effective_config = effective
        self._settings = copy.deepcopy(decoded.settings)
        self._sources = sources
        self._schema_version = decoded.schema_version
        self._revision = revision
        self._loaded = True
        self._diagnostics = ConfigDiagnostics(
            source=source,
            schema_version=decoded.schema_version,
            recovered=recovered,
            migrated_from=migrated_from,
            future_schema=future_schema,
            quarantined_paths=tuple(quarantined),
            migration_backups=tuple(migration_backups),
            messages=tuple(messages),
        )
        return ConfigDocument(
            schema_version=decoded.schema_version,
            stored_config=decoded.stored_config,
            effective_config=effective,
            settings=copy.deepcopy(decoded.settings),
            value_sources=dict(sources),
            revision=revision,
        )

    def save(
        self,
        config: AppConfig,
        *,
        expected_revision: str | _ExpectedRevisionUnset | None = _EXPECTED_REVISION_UNSET,
        persist_environment_overrides: bool = False,
    ) -> Path:
        if not self._loaded and self.paths.config_file.exists():
            self.load_document()
        config.validate()
        config = replace(config, theme=normalize_theme_identifier(config.theme))
        stored = config
        if self._loaded and not persist_environment_overrides:
            replacements = {
                name: getattr(self._stored_config, name)
                for name, source in self._sources.items()
                if source == "environment"
            }
            if replacements:
                stored = replace(stored, **replacements)
        guarded_revision = (
            self._revision
            if isinstance(expected_revision, _ExpectedRevisionUnset)
            else expected_revision
        )
        return self.save_document(
            stored,
            self._settings,
            expected_revision=guarded_revision,
        )

    def save_document(
        self,
        config: AppConfig,
        settings: Mapping[str, Any],
        *,
        expected_revision: str | _ExpectedRevisionUnset | None = _EXPECTED_REVISION_UNSET,
    ) -> Path:
        config.validate()
        config = replace(config, theme=normalize_theme_identifier(config.theme))
        if not self._loaded and self.paths.config_file.exists():
            self.load_document()
        guarded_revision = (
            self._revision
            if isinstance(expected_revision, _ExpectedRevisionUnset)
            else expected_revision
        )
        if self._diagnostics.future_schema:
            raise ConfigurationError(
                "This configuration was written by a newer GUC Mail version and is read-only "
                "here. Upgrade GUC Mail before changing settings."
            )
        _validate_settings_mapping(settings)
        mapping = self._build_mapping(config, settings)
        _reject_plaintext_secrets(mapping)
        content = _mapping_to_toml(mapping).encode("utf-8")
        self.paths.ensure()
        lkg_warning: str | None = None
        lock_path = self.paths.config_file.with_name(self.paths.config_file.name + ".lock")
        with _interprocess_file_lock(lock_path):
            current_revision = _file_revision(self.paths.config_file)
            if current_revision != guarded_revision:
                raise ConfigurationError(
                    "Settings changed in another process. Reload them before applying your changes."
                )
            self._record_previous_revision()
            _atomic_write_bytes(self.paths.config_file, content)
            try:
                _atomic_write_bytes(self.last_known_good_path, content)
            except OSError:
                lkg_warning = "Configuration was saved, but the recovery copy could not be updated."
            self._prune_revisions()

        decoded = _decode_document(content)
        effective, sources = _apply_environment(decoded.stored_config)
        self._mapping = copy.deepcopy(decoded.mapping)
        self._stored_config = decoded.stored_config
        self._effective_config = effective
        self._settings = copy.deepcopy(decoded.settings)
        self._sources = sources
        self._schema_version = decoded.schema_version
        self._revision = hashlib.sha256(content).hexdigest()
        self._loaded = True
        self._diagnostics = ConfigDiagnostics(
            source="primary",
            schema_version=decoded.schema_version,
            messages=(lkg_warning,) if lkg_warning else (),
        )
        return self.paths.config_file

    def _repair_document(
        self,
        content: bytes,
        *,
        expected_revision: str | None,
        baseline_known: bool,
        update_recovery: bool = False,
    ) -> str | None:
        """Repair only the primary snapshot inspected by this load operation."""
        if not baseline_known:
            raise OSError("The primary configuration could not be read; repair was not saved.")
        lock_path = self.paths.config_file.with_name(self.paths.config_file.name + ".lock")
        with _interprocess_file_lock(lock_path):
            if _file_revision(self.paths.config_file) != expected_revision:
                raise ConfigurationError(
                    "Settings changed in another process during recovery. Reload them before "
                    "applying your changes."
                )
            _atomic_write_bytes(self.paths.config_file, content)
            if update_recovery:
                # Failure of the secondary copy must not disguise a successful primary repair.
                try:
                    _atomic_write_bytes(self.last_known_good_path, content)
                except OSError:
                    return "Configuration was repaired, but the recovery copy could not be updated."
        return None

    def set(self, key: str, raw_value: str) -> AppConfig:
        valid = {item.name for item in fields(AppConfig)}
        if key not in valid:
            raise ConfigurationError(f"Unknown configuration setting: {key}")
        document = self.load_document()
        if document.value_sources.get(key) == "environment":
            env_name = ENV_PREFIX + key.upper()
            raise ConfigurationError(
                f"{key} is overridden by {env_name}; remove that override before editing it."
            )
        converter = _CONVERTERS.get(key, str)
        try:
            value = converter(raw_value)
        except (TypeError, ValueError) as exc:
            raise ConfigurationError(f"Invalid value for {key}: {exc}") from exc
        updated = replace(document.stored_config, **{key: value}).validate()
        self.save_document(updated, document.settings, expected_revision=document.revision)
        return self.load()

    def reset(self, key: str) -> AppConfig:
        valid = {item.name for item in fields(AppConfig)}
        if key not in valid:
            raise ConfigurationError(f"Unknown configuration setting: {key}")
        document = self.load_document()
        if document.value_sources.get(key) == "environment":
            env_name = ENV_PREFIX + key.upper()
            raise ConfigurationError(
                f"{key} is overridden by {env_name}; remove that override before resetting it."
            )
        default = getattr(AppConfig(), key)
        updated = replace(document.stored_config, **{key: default}).validate()
        self.save_document(updated, document.settings, expected_revision=document.revision)
        return self.load()

    def _build_mapping(self, config: AppConfig, settings: Mapping[str, Any]) -> dict[str, Any]:
        mapping = copy.deepcopy(self._mapping) if self._mapping else _default_document()
        version = mapping.get("schema_version", CURRENT_CONFIG_SCHEMA_VERSION)
        if not isinstance(version, int) or isinstance(version, bool):
            version = CURRENT_CONFIG_SCHEMA_VERSION
        mapping["schema_version"] = max(version, CURRENT_CONFIG_SCHEMA_VERSION)
        existing_section = mapping.get("gucmail")
        section = copy.deepcopy(existing_section) if isinstance(existing_section, dict) else {}
        for key, value in asdict(config).items():
            if value is None:
                section.pop(key, None)
            else:
                section[key] = value
        mapping["gucmail"] = section
        mapping["settings"] = copy.deepcopy(dict(settings))
        return mapping

    def _quarantine(self, path: Path, existing: bytes | None) -> Path | None:
        try:
            content = existing if existing is not None else path.read_bytes()
            stamp = datetime.now(UTC).strftime("%Y%m%dT%H%M%SZ")
            target = path.with_name(f"{path.stem}.corrupt.{stamp}.{uuid4().hex[:8]}{path.suffix}")
            _atomic_write_bytes(target, content)
            return target
        except OSError:
            return None

    def _migration_backup(self, existing: bytes | None, from_version: int) -> Path | None:
        if existing is None:
            return None
        try:
            stamp = datetime.now(UTC).strftime("%Y%m%dT%H%M%SZ")
            target = self.paths.config_file.with_name(
                f"{self.paths.config_file.stem}.migration-v{from_version}.{stamp}.toml"
            )
            _atomic_write_bytes(target, existing)
            return target
        except OSError:
            return None

    def _record_previous_revision(self) -> None:
        target = self.paths.config_file
        if not target.exists():
            return
        try:
            content = target.read_bytes()
            _decode_document(content)
            digest = hashlib.sha256(content).hexdigest()[:12]
            stamp = datetime.now(UTC).strftime("%Y%m%dT%H%M%S.%fZ")
            revision_path = self.revisions_directory / f"{stamp}-{digest}.toml"
            _atomic_write_bytes(revision_path, content)
        except (OSError, UnicodeError, tomllib.TOMLDecodeError, ConfigurationError):
            return

    def _prune_revisions(self) -> None:
        if not self.revisions_directory.exists():
            return
        revisions = sorted(self.revisions_directory.glob("*.toml"), reverse=True)
        for stale in revisions[CONFIG_HISTORY_LIMIT:]:
            try:
                stale.unlink()
            except OSError:
                continue


def _apply_environment(config: AppConfig) -> tuple[AppConfig, dict[str, str]]:
    values = asdict(config)
    sources = {item.name: "configuration" for item in fields(AppConfig)}
    for field_info in fields(AppConfig):
        env_name = ENV_PREFIX + field_info.name.upper()
        if env_name not in os.environ:
            continue
        raw = os.environ[env_name]
        converter = _CONVERTERS.get(field_info.name, str)
        try:
            values[field_info.name] = converter(raw)
        except (ValueError, TypeError) as exc:
            raise ConfigurationError(f"Invalid value for {env_name}: {exc}") from exc
        sources[field_info.name] = "environment"
    theme = values["theme"]
    if isinstance(theme, str):
        values["theme"] = normalize_theme_identifier(theme)
    try:
        effective = AppConfig(**values).validate()
    except TypeError as exc:
        raise ConfigurationError(f"Invalid configuration: {exc}") from exc
    return effective, sources


def _decode_document(content: bytes) -> _DecodedDocument:
    text = content.decode("utf-8")
    parsed = tomllib.loads(text)
    if not isinstance(parsed, dict):
        raise ConfigurationError("Configuration must be a TOML table.")
    _reject_plaintext_secrets(parsed)
    mapping, migrated_from, migration_messages, future_schema = _migrate_mapping(parsed)
    schema = mapping.get("schema_version", CURRENT_CONFIG_SCHEMA_VERSION)
    if not isinstance(schema, int) or isinstance(schema, bool) or schema < 1:
        raise ConfigurationError("schema_version must be a positive integer.")
    section = mapping.get("gucmail", {})
    if not isinstance(section, dict):
        raise ConfigurationError("Configuration section [gucmail] must be a table.")
    valid = {item.name for item in fields(AppConfig)}
    known = {name: value for name, value in section.items() if name in valid}
    try:
        candidate = AppConfig(**known)
        stored = (
            replace(candidate, theme=normalize_theme_identifier(candidate.theme))
            if isinstance(candidate.theme, str)
            else candidate
        ).validate()
    except TypeError as exc:
        raise ConfigurationError(f"Invalid configuration: {exc}") from exc
    settings = mapping.get("settings", {})
    if not isinstance(settings, dict):
        raise ConfigurationError("Configuration section [settings] must be a table.")
    _validate_settings_mapping(settings)
    return _DecodedDocument(
        schema_version=schema,
        stored_config=stored,
        settings=_decode_setting_nulls(settings),
        mapping=copy.deepcopy(mapping),
        migrated_from=migrated_from,
        migration_messages=migration_messages,
        future_schema=future_schema,
    )


def _migrate_mapping(
    source: Mapping[str, Any],
) -> tuple[dict[str, Any], int | None, list[str], bool]:
    mapping = copy.deepcopy(dict(source))
    raw_version = mapping.get("schema_version", 0)
    if not isinstance(raw_version, int) or isinstance(raw_version, bool) or raw_version < 0:
        raise ConfigurationError("schema_version must be a non-negative integer.")
    if raw_version > CURRENT_CONFIG_SCHEMA_VERSION:
        return mapping, None, [], True
    original_version = raw_version
    messages: list[str] = []
    version = raw_version
    while version < CURRENT_CONFIG_SCHEMA_VERSION:
        if version == 0:
            mapping = _migrate_v0_to_v1(mapping)
        elif version == 1:
            mapping = _migrate_v1_to_v2(mapping)
            messages.append("Appearance and adaptive-layout settings were migrated.")
        elif version == 2:
            mapping = _migrate_v2_to_v3(mapping)
            messages.append(
                "Storage settings now use separate Exchange quota thresholds; legacy values "
                "were preserved for review."
            )
        elif version == 3:
            mapping = _migrate_v3_to_v4(mapping)
            messages.append("Legacy theme and shortcut identifiers were normalized.")
        elif version == 4:
            mapping = _migrate_v4_to_v5(mapping)
            messages.append(
                "Unverified generic mailbox capacity was archived; capacity remains unknown "
                "until reported. Independent Exchange thresholds were preserved."
            )
        version += 1
        mapping["schema_version"] = version
    return mapping, (original_version if original_version != version else None), messages, False


def _migrate_v0_to_v1(mapping: dict[str, Any]) -> dict[str, Any]:
    result = copy.deepcopy(mapping)
    known = {item.name for item in fields(AppConfig)}
    if "gucmail" not in result:
        section: dict[str, Any] = {}
        for key in tuple(result):
            if key in known:
                section[key] = result.pop(key)
        result["gucmail"] = section
    elif not isinstance(result["gucmail"], dict):
        raise ConfigurationError("Configuration section [gucmail] must be a table.")
    result.setdefault("settings", {})
    result["schema_version"] = 1
    return result


def _migrate_v1_to_v2(mapping: dict[str, Any]) -> dict[str, Any]:
    result = copy.deepcopy(mapping)
    section = result.setdefault("gucmail", {})
    settings = result.setdefault("settings", {})
    if not isinstance(section, dict) or not isinstance(settings, dict):
        raise ConfigurationError("Configuration tables are malformed.")
    theme = section.get("theme")
    if isinstance(theme, str):
        section["theme"] = normalize_theme_identifier(theme)
    layout_fields = {
        "folder_pane_width": ("layout.sidebar_ratio", 0.22),
        "message_list_width": ("layout.message_list_ratio", 0.36),
        "preview_pane_width": ("layout.preview_ratio", 0.42),
    }
    metadata = result.setdefault("migration_metadata", {})
    if not isinstance(metadata, dict):
        raise ConfigurationError("migration_metadata must be a table.")
    legacy_layout = metadata.setdefault("legacy_layout", {})
    if not isinstance(legacy_layout, dict):
        raise ConfigurationError("migration_metadata.legacy_layout must be a table.")
    for old_name, (setting_id, default_ratio) in layout_fields.items():
        if old_name not in section:
            continue
        old_value = section.pop(old_name)
        legacy_layout[old_name] = old_value
        ratio = default_ratio
        if isinstance(old_value, (int, float)) and not isinstance(old_value, bool):
            ratio = min(0.75, max(0.15, float(old_value) / 120.0))
        settings.setdefault(setting_id, round(ratio, 4))
    result["schema_version"] = 2
    return result


def _migrate_v2_to_v3(mapping: dict[str, Any]) -> dict[str, Any]:
    result = copy.deepcopy(mapping)
    section = result.setdefault("gucmail", {})
    settings = result.setdefault("settings", {})
    metadata = result.setdefault("migration_metadata", {})
    if (
        not isinstance(section, dict)
        or not isinstance(settings, dict)
        or not isinstance(metadata, dict)
    ):
        raise ConfigurationError("Configuration tables are malformed.")
    legacy_value = section.pop("mailbox_quota_mb", result.pop("mailbox_quota_mb", None))
    if legacy_value is not None:
        metadata["legacy_mailbox_quota_mb"] = legacy_value
        metadata["quota_migration_status"] = "requires_review"
    settings.setdefault("storage.quota_auto_detect", True)
    settings.setdefault("storage.prefer_server_quota", True)
    settings.setdefault("storage.issue_warning_source", "unknown")
    settings.setdefault("storage.prohibit_send_mb", 92.0)
    settings.setdefault("storage.prohibit_send_source", "known_guc_fallback")
    settings.setdefault("storage.prohibit_send_receive_source", "unknown")
    result["schema_version"] = 3
    return result


def _migrate_v3_to_v4(mapping: dict[str, Any]) -> dict[str, Any]:
    """Normalize identifiers without inventing semantics for legacy values."""

    result = copy.deepcopy(mapping)
    section = result.setdefault("gucmail", {})
    settings = result.setdefault("settings", {})
    metadata = result.setdefault("migration_metadata", {})
    if (
        not isinstance(section, dict)
        or not isinstance(settings, dict)
        or not isinstance(metadata, dict)
    ):
        raise ConfigurationError("Configuration tables are malformed.")

    legacy_theme = section.pop("theme_name", result.pop("theme_name", None))
    if legacy_theme is not None and "theme" not in section:
        section["theme"] = legacy_theme
        metadata["legacy_theme_name"] = legacy_theme
    theme = section.get("theme")
    if isinstance(theme, str):
        section["theme"] = normalize_theme_identifier(theme)

    shortcut_fields = {
        "palette_shortcut": "palette.primary_shortcut",
        "command_palette_shortcut": "palette.primary_shortcut",
        "secondary_palette_shortcut": "palette.secondary_shortcut",
    }
    legacy_shortcuts = metadata.setdefault("legacy_shortcuts", {})
    if not isinstance(legacy_shortcuts, dict):
        raise ConfigurationError("migration_metadata.legacy_shortcuts must be a table.")
    for old_name, setting_id in shortcut_fields.items():
        old_value = section.pop(old_name, result.pop(old_name, None))
        if old_value is None:
            continue
        legacy_shortcuts[old_name] = old_value
        if isinstance(old_value, str):
            settings.setdefault(setting_id, old_value.casefold().replace(" ", ""))

    result["schema_version"] = 4
    return result


def _migrate_v4_to_v5(mapping: dict[str, Any]) -> dict[str, Any]:
    """Preserve the obsolete generic limit without assigning it threshold semantics."""
    result = copy.deepcopy(mapping)
    settings = result.setdefault("settings", {})
    metadata = result.setdefault("migration_metadata", {})
    if not isinstance(settings, dict) or not isinstance(metadata, dict):
        raise ConfigurationError("Configuration tables are malformed.")
    if "storage.fallback_capacity_mb" in settings:
        metadata["legacy_fallback_capacity_mb"] = settings.pop("storage.fallback_capacity_mb")
        metadata["capacity_migration_status"] = "unverified_generic_capacity_archived"
    result["schema_version"] = 5
    return result


def _default_document() -> dict[str, Any]:
    return {
        "schema_version": CURRENT_CONFIG_SCHEMA_VERSION,
        "gucmail": {key: value for key, value in asdict(AppConfig()).items() if value is not None},
        "settings": {},
    }


def _reject_plaintext_secrets(mapping: Mapping[str, Any], path: tuple[str, ...] = ()) -> None:
    """Reject secret-bearing values from the ordinary configuration document.

    Secret *references* and status metadata are deliberately allowed. Provider
    webhook URLs and authorization headers often embed credentials, so they are
    treated as secrets even when their key is not literally named ``password``.
    """

    for key, value in mapping.items():
        if not isinstance(key, str):
            raise ConfigurationError("Configuration object keys must be text.")
        normalized = re.sub(r"[^a-z0-9]+", "_", key.casefold()).strip("_")
        ancestors = _secret_path_tokens(path)
        safe_metadata = normalized.endswith(_SAFE_SECRET_METADATA_SUFFIXES)
        secret_key = not safe_metadata and (
            normalized in _SECRET_KEY_PARTS
            or any(normalized.endswith(f"_{part}") for part in _SECRET_KEY_PARTS)
            or (
                normalized in {"url", "uri"}
                and bool(
                    ancestors
                    & {
                        "discord",
                        "integrations",
                        "providers",
                        "telegram",
                        "webhook",
                        "webhooks",
                    }
                )
            )
        )
        secure_reference = (
            isinstance(value, str)
            and value.startswith("keyring://")
            and not any(ord(character) < 32 for character in value)
        )
        if secret_key and not secure_reference:
            location = ".".join((*path, key))
            raise ConfigurationError(
                f"Secret field {location!r} is not allowed in normal settings; store only a "
                "secure secret reference."
            )
        if isinstance(value, Mapping):
            _reject_plaintext_secrets(value, (*path, key))
        elif isinstance(value, (list, tuple)):
            _reject_plaintext_secrets_in_sequence(value, (*path, key))


def _reject_plaintext_secrets_in_sequence(
    values: list[Any] | tuple[Any, ...], path: tuple[str, ...]
) -> None:
    for index, item in enumerate(values):
        item_path = (*path, str(index))
        if isinstance(item, Mapping):
            _reject_plaintext_secrets(item, item_path)
        elif isinstance(item, (list, tuple)):
            _reject_plaintext_secrets_in_sequence(item, item_path)


def _secret_path_tokens(path: tuple[str, ...]) -> set[str]:
    """Return both compound and component tokens for dotted/nested setting paths."""

    tokens: set[str] = set()
    for part in path:
        components = re.findall(r"[a-z0-9]+", part.casefold())
        if not components:
            continue
        tokens.update(components)
        tokens.add("_".join(components))
    return tokens


def _validate_settings_mapping(settings: Mapping[str, Any]) -> None:
    for key, value in settings.items():
        if not isinstance(key, str) or not key or any(ord(character) < 32 for character in key):
            raise ConfigurationError("Setting IDs must be non-empty printable strings.")
        _validate_toml_value(value, setting_id=key)


def _validate_toml_value(value: Any, *, setting_id: str) -> None:
    if value is None:
        return
    if isinstance(value, (str, bool, int, datetime, date, time)):
        return
    if isinstance(value, float):
        if not math.isfinite(value):
            raise ConfigurationError(f"Setting {setting_id} must be a finite number.")
        return
    if isinstance(value, (list, tuple)):
        for item in value:
            _validate_toml_value(item, setting_id=setting_id)
        return
    if isinstance(value, dict):
        _validate_settings_mapping(value)
        return
    raise ConfigurationError(f"Setting {setting_id} cannot be stored in TOML.")


def _file_revision(path: Path) -> str | None:
    try:
        content = path.read_bytes()
    except FileNotFoundError:
        return None
    return hashlib.sha256(content).hexdigest()


@contextmanager
def _interprocess_file_lock(path: Path, *, timeout_seconds: float = 5.0) -> Iterator[None]:
    """Hold a small cross-platform advisory lock around compare-and-swap writes."""

    path.parent.mkdir(parents=True, exist_ok=True)
    handle = path.open("a+b")
    handle.seek(0, os.SEEK_END)
    if handle.tell() == 0:
        handle.write(b"0")
        handle.flush()
    deadline = time_module.monotonic() + timeout_seconds
    acquired = False
    try:
        while not acquired:
            try:
                handle.seek(0)
                if os.name == "nt":
                    import msvcrt

                    msvcrt.locking(handle.fileno(), msvcrt.LK_NBLCK, 1)
                else:
                    fcntl = importlib.import_module("fcntl")
                    fcntl.flock(handle.fileno(), fcntl.LOCK_EX | fcntl.LOCK_NB)
                acquired = True
            except OSError as exc:
                if time_module.monotonic() >= deadline:
                    raise ConfigurationError(
                        "Another GUC Mail process is updating Settings. Try again shortly."
                    ) from exc
                time_module.sleep(0.05)
        yield
    finally:
        if acquired:
            try:
                handle.seek(0)
                if os.name == "nt":
                    import msvcrt

                    msvcrt.locking(handle.fileno(), msvcrt.LK_UNLCK, 1)
                else:
                    fcntl = importlib.import_module("fcntl")
                    fcntl.flock(handle.fileno(), fcntl.LOCK_UN)
            except OSError:
                pass
        handle.close()


def _atomic_write_bytes(target: Path, content: bytes) -> None:
    target.parent.mkdir(parents=True, exist_ok=True)
    fd, temporary_name = tempfile.mkstemp(
        prefix=f".{target.name}.", suffix=".tmp", dir=target.parent
    )
    try:
        with os.fdopen(fd, "wb") as handle:
            handle.write(content)
            handle.flush()
            os.fsync(handle.fileno())
        # A Windows reader/scanner can briefly deny replacement despite a closed writer.
        # Keep the same durable temporary file and advisory lock throughout a bounded retry.
        delays = (0.02, 0.05, 0.1, 0.2, 0.4)
        for attempt in range(len(delays) + 1):
            try:
                os.replace(temporary_name, target)
                break
            except OSError as exc:
                if getattr(exc, "winerror", None) not in {5, 32, 33} or attempt == len(delays):
                    raise
                time_module.sleep(delays[attempt])
        _fsync_directory(target.parent)
    except BaseException:
        Path(temporary_name).unlink(missing_ok=True)
        raise


def _fsync_directory(directory: Path) -> None:
    """Best-effort directory synchronization after an atomic replacement."""

    if os.name == "nt":
        return
    descriptor: int | None = None
    try:
        descriptor = os.open(directory, os.O_RDONLY)
        os.fsync(descriptor)
    except OSError:
        return
    finally:
        if descriptor is not None:
            os.close(descriptor)


def _toml_string(value: str) -> str:
    escaped = (
        value.replace("\\", "\\\\")
        .replace('"', '\\"')
        .replace("\b", "\\b")
        .replace("\t", "\\t")
        .replace("\n", "\\n")
        .replace("\f", "\\f")
        .replace("\r", "\\r")
    )
    return f'"{escaped}"'


def _toml_key(value: str) -> str:
    return value if _BARE_TOML_KEY.fullmatch(value) else _toml_string(value)


def _decode_setting_nulls(value: Any) -> Any:
    """TOML has no null scalar; preserve an explicit optional-setting override."""
    if isinstance(value, dict):
        if value == {"__gucmail_null__": True}:
            return None
        return {key: _decode_setting_nulls(item) for key, item in value.items()}
    if isinstance(value, list):
        return [_decode_setting_nulls(item) for item in value]
    return value


def _toml_value(value: Any) -> str:
    if value is None:
        return "{__gucmail_null__ = true}"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, str):
        return _toml_string(value)
    if isinstance(value, int):
        return str(value)
    if isinstance(value, float):
        if not math.isfinite(value):
            raise ConfigurationError("TOML does not support non-finite settings values.")
        return repr(value)
    if isinstance(value, (datetime, date, time)):
        return value.isoformat()
    if isinstance(value, (list, tuple)):
        return "[" + ", ".join(_toml_value(item) for item in value) + "]"
    if isinstance(value, dict):
        pairs = ", ".join(
            f"{_toml_key(str(key))} = {_toml_value(item)}" for key, item in value.items()
        )
        return "{" + pairs + "}"
    raise ConfigurationError(f"Unsupported TOML value type: {type(value).__name__}")


def _mapping_to_toml(mapping: Mapping[str, Any]) -> str:
    lines = ["# gucmail settings. Never put passwords here; they live in your system keyring."]

    def emit_table(path: tuple[str, ...], table: Mapping[str, Any]) -> None:
        scalar_items = [(key, value) for key, value in table.items() if not isinstance(value, dict)]
        child_items = [(key, value) for key, value in table.items() if isinstance(value, dict)]
        if path:
            if lines[-1] != "":
                lines.append("")
            lines.append("[" + ".".join(_toml_key(part) for part in path) + "]")
        for key, value in scalar_items:
            lines.append(f"{_toml_key(str(key))} = {_toml_value(value)}")
        for key, child in child_items:
            emit_table((*path, str(key)), child)

    emit_table((), mapping)
    return "\n".join(lines).rstrip() + "\n"



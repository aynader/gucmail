"""Versioned, crash-safe, non-secret application configuration.

The public :class:`AppConfig` remains a flat dataclass for compatibility with the
first-pass CLI and service layer.  The on-disk document is richer: it has an
explicit schema version, a namespace for extensible settings, bounded revision
history, a last-known-good copy, and migration metadata.  Unknown keys are kept
when an older client saves a newer document.
"""

